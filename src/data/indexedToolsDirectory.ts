export function getToolsByCategorySlug(slug: string): PlanningToolItem[] {
  return ALL_INDEXED_TOOLS.filter((t) => t.categorySlug === slug);
}

export function searchAllTools(query: string): PlanningToolItem[] {
  if (!query.trim()) return ALL_INDEXED_TOOLS;
  const lower = query.toLowerCase();
  return ALL_INDEXED_TOOLS.filter((t) => 
    t.name.toLowerCase().includes(lower) ||
    t.bestFor.toLowerCase().includes(lower) ||
    (t.categoryName && t.categoryName.toLowerCase().includes(lower)) ||
    t.keyFeatures.some(f => f.toLowerCase().includes(lower)) ||
    (t.featuredBadge && t.featuredBadge.toLowerCase().includes(lower))
  );
}
